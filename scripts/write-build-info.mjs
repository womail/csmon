#!/usr/bin/env node
/** Writes lib/build-info.generated.ts from git (or placeholders when git is missing). */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "lib/build-info.generated.ts");

function git(cmd) {
  return execSync(cmd, { cwd: root, encoding: "utf8" }).trim();
}

let commit = "unknown";
let buildDate = new Date().toISOString().slice(0, 10);
try {
  commit = git("git rev-parse --short HEAD");
  buildDate = git("git log -1 --format=%cI").slice(0, 10);
} catch {
  /* shallow Docker context or no git */
}

const body = `/** Generated by scripts/write-build-info.mjs — do not edit. */
export const APP_BUILD_COMMIT = ${JSON.stringify(commit)};
export const APP_BUILD_DATE = ${JSON.stringify(buildDate)};
`;

fs.writeFileSync(out, body);
console.log(`build-info: ${commit} @ ${buildDate}`);
