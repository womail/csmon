# shellcheck shell=bash
# Shared helpers for csmon-deploy.

set -euo pipefail

_csmon_deploy_lib_loaded="${_csmon_deploy_lib_loaded:-}"

if [[ -n "${_csmon_deploy_lib_loaded}" ]]; then
  return 0 2>/dev/null || true
fi
_csmon_deploy_lib_loaded=1

CSMON_DEPLOY_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CSMON_PROJECT_ROOT="$(cd "${CSMON_DEPLOY_SCRIPT_DIR}/.." && pwd)"
CSMON_DEPLOY_DIR="${CSMON_PROJECT_ROOT}/deploy"
CSMON_MANIFEST="${CSMON_DEPLOY_DIR}/manifest.sh"

if [[ ! -f "${CSMON_MANIFEST}" ]]; then
  echo "csmon-deploy: missing ${CSMON_MANIFEST}" >&2
  exit 1
fi
# shellcheck source=../../deploy/manifest.sh
source "${CSMON_MANIFEST}"

CSMON_DEPLOY_STATE_ROOT="${CSMON_DEPLOY_STATE_ROOT:-${CSMON_PROJECT_ROOT}/.csmon-deploy}"
CSMON_SLOTS_DIR="${CSMON_DEPLOY_STATE_ROOT}/slots"
CSMON_SHARED_DIR="${CSMON_DEPLOY_STATE_ROOT}/shared"
CSMON_SNAPSHOTS_DIR="${CSMON_DEPLOY_STATE_ROOT}/snapshots"
CSMON_ARCHIVE_DIR="${CSMON_DEPLOY_STATE_ROOT}/archives"
CSMON_STATE_FILE="${CSMON_DEPLOY_STATE_ROOT}/state.env"
CSMON_LOG_DIR="${CSMON_DEPLOY_STATE_ROOT}/logs"

CSMON_SLOT_PRODUCTION="production"
CSMON_SLOT_PREPRODUCTION="preproduction"

_csmon_color() {
  if [[ -t 1 ]] && command -v tput >/dev/null 2>&1; then
    tput setaf "$1" 2>/dev/null || true
  fi
}

_csmon_reset() {
  if [[ -t 1 ]] && command -v tput >/dev/null 2>&1; then
    tput sgr0 2>/dev/null || true
  fi
}

csmon_info() { echo "$(_csmon_color 6)▸$(_csmon_reset) $*"; }
csmon_ok() { echo "$(_csmon_color 2)✓$(_csmon_reset) $*"; }
csmon_warn() { echo "$(_csmon_color 3)!$(_csmon_reset) $*" >&2; }
csmon_err() { echo "$(_csmon_color 1)✗$(_csmon_reset) $*" >&2; }

csmon_die() {
  csmon_err "$*"
  exit 1
}

csmon_require_cmd() {
  local c
  for c in "$@"; do
    command -v "$c" >/dev/null 2>&1 || csmon_die "Required command not found: ${c}"
  done
}

csmon_ensure_layout() {
  mkdir -p "${CSMON_SLOTS_DIR}" "${CSMON_SHARED_DIR}" "${CSMON_SNAPSHOTS_DIR}" \
    "${CSMON_ARCHIVE_DIR}" "${CSMON_LOG_DIR}" \
    "${CSMON_SHARED_DIR}/env" "${CSMON_SHARED_DIR}/data"
}

csmon_state_load() {
  CSMON_RUNTIME=""
  CSMON_PRODUCTION_PATH=""
  CSMON_PREPRODUCTION_PATH=""
  CSMON_PREVIOUS_PATH=""
  CSMON_PREPROD_DATA_SNAPSHOT=""
  CSMON_PRODUCTION_RUNNING="0"
  CSMON_PREPRODUCTION_RUNNING="0"
  CSMON_GIT_REMOTE=""
  if [[ -f "${CSMON_STATE_FILE}" ]]; then
    # shellcheck disable=SC1090
    source "${CSMON_STATE_FILE}"
  fi
  CSMON_PRODUCTION_PATH="${CSMON_PRODUCTION_PATH:-${CSMON_PROJECT_ROOT}}"
  CSMON_PREPRODUCTION_PATH="${CSMON_PREPRODUCTION_PATH:-${CSMON_SLOTS_DIR}/preproduction}"
  CSMON_GIT_REMOTE="${CSMON_GIT_REMOTE:-origin}"
}

csmon_state_save() {
  csmon_ensure_layout
  cat >"${CSMON_STATE_FILE}" <<EOF
# Generated by csmon-deploy — safe to edit GIT_REMOTE or RUNTIME
CSMON_RUNTIME=${CSMON_RUNTIME:-}
CSMON_PRODUCTION_PATH=${CSMON_PRODUCTION_PATH}
CSMON_PREPRODUCTION_PATH=${CSMON_PREPRODUCTION_PATH}
CSMON_PREVIOUS_PATH=${CSMON_PREVIOUS_PATH:-}
CSMON_PREPROD_DATA_SNAPSHOT=${CSMON_PREPROD_DATA_SNAPSHOT:-}
CSMON_PRODUCTION_RUNNING=${CSMON_PRODUCTION_RUNNING:-0}
CSMON_PREPRODUCTION_RUNNING=${CSMON_PREPRODUCTION_RUNNING:-0}
CSMON_GIT_REMOTE=${CSMON_GIT_REMOTE:-origin}
EOF
}

csmon_init_if_needed() {
  csmon_ensure_layout
  csmon_state_load
  if [[ ! -f "${CSMON_STATE_FILE}" ]]; then
    csmon_info "First run — initializing deploy state under ${CSMON_DEPLOY_STATE_ROOT}"
    CSMON_PRODUCTION_PATH="${CSMON_PROJECT_ROOT}"
    CSMON_PREPRODUCTION_PATH="${CSMON_SLOTS_DIR}/preproduction"
    csmon_state_save
    csmon_sync_shared_env_from_production
    csmon_sync_shared_data_from_production
  fi
}

csmon_slot_port() {
  case "$1" in
    production | "${CSMON_SLOT_PRODUCTION}") echo "${CSMON_PORT_PRODUCTION}" ;;
    preproduction | preprod | "${CSMON_SLOT_PREPRODUCTION}") echo "${CSMON_PORT_PREPRODUCTION}" ;;
    *) csmon_die "Unknown slot for port: $1" ;;
  esac
}

csmon_slot_path() {
  case "$1" in
    production | "${CSMON_SLOT_PRODUCTION}") echo "${CSMON_PRODUCTION_PATH}" ;;
    preproduction | preprod | "${CSMON_SLOT_PREPRODUCTION}") echo "${CSMON_PREPRODUCTION_PATH}" ;;
    *)
      if [[ -d "${CSMON_SLOTS_DIR}/$1" ]]; then
        echo "${CSMON_SLOTS_DIR}/$1"
      else
        csmon_die "Unknown slot: $1"
      fi
      ;;
  esac
}

csmon_docker_compose() {
  if docker compose version >/dev/null 2>&1; then
    echo "docker compose"
  elif command -v docker-compose >/dev/null 2>&1; then
    echo "docker-compose"
  else
    csmon_die "Docker Compose is not available"
  fi
}

csmon_compose_project() {
  local slot="$1"
  echo "csmon-${slot}"
}

csmon_runtime_resolve() {
  csmon_state_load
  if [[ -n "${CSMON_RUNTIME}" ]]; then
    echo "${CSMON_RUNTIME}"
    return
  fi
  if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
    echo "docker"
  elif command -v pnpm >/dev/null 2>&1; then
    echo "node"
  else
    csmon_die "Set RUNTIME via menu (docker or node); neither Docker nor pnpm is ready"
  fi
}

csmon_rsync_excludes() {
  local args=()
  local x
  for x in "${CSMON_COPY_EXCLUDE[@]}"; do
    args+=(--exclude "$x")
  done
  printf '%s\n' "${args[@]}"
}

csmon_copy_tree() {
  local src="$1" dst="$2"
  csmon_require_cmd rsync
  mkdir -p "$dst"
  # shellcheck disable=SC2046
  rsync -a --delete $(csmon_rsync_excludes) "${src}/" "${dst}/"
}

csmon_shared_env_dir() {
  echo "${CSMON_SHARED_DIR}/env"
}

csmon_shared_data_dir() {
  echo "${CSMON_SHARED_DIR}/data"
}

csmon_sync_shared_env_from_production() {
  local prod envdir f base
  prod="$(csmon_slot_path production)"
  envdir="$(csmon_shared_env_dir)"
  mkdir -p "${envdir}"
  for f in "${CSMON_RETAIN_ENV_FILES[@]}"; do
    base="$(basename "$f")"
    if [[ -f "${prod}/${f}" ]]; then
      cp -a "${prod}/${f}" "${envdir}/${base}"
    fi
  done
}

csmon_link_env_into_slot() {
  local slot_path="$1"
  local envdir f base
  envdir="$(csmon_shared_env_dir)"
  for f in "${CSMON_RETAIN_ENV_FILES[@]}"; do
    base="$(basename "$f")"
    if [[ -f "${envdir}/${base}" ]]; then
      ln -sf "${envdir}/${base}" "${slot_path}/${f}"
    fi
  done
}

csmon_sync_shared_data_from_production() {
  local prod="${CSMON_PRODUCTION_PATH:-${CSMON_PROJECT_ROOT}}"
  local shared="$(csmon_shared_data_dir)"
  local src="${prod}/${CSMON_DATA_DIR_NAME}"
  if [[ -d "${src}" ]]; then
    csmon_require_cmd rsync
    mkdir -p "${shared}"
    rsync -a "${src}/" "${shared}/"
  fi
}

csmon_data_dir_for_slot() {
  local slot="$1"
  case "$slot" in
    production | "${CSMON_SLOT_PRODUCTION}")
      echo "$(csmon_shared_data_dir)"
      ;;
    preproduction | preprod | "${CSMON_SLOT_PREPRODUCTION}")
      if [[ -n "${CSMON_PREPROD_DATA_SNAPSHOT:-}" && -d "${CSMON_PREPROD_DATA_SNAPSHOT}" ]]; then
        echo "${CSMON_PREPROD_DATA_SNAPSHOT}"
      else
        echo "${CSMON_SNAPSHOTS_DIR}/preproduction-data"
      fi
      ;;
    *)
      echo "${CSMON_SNAPSHOTS_DIR}/slot-${slot}-data"
      ;;
  esac
}

csmon_snapshot_production_data() {
  local dest="$1"
  local shared
  shared="$(csmon_shared_data_dir)"
  csmon_require_cmd rsync
  mkdir -p "${dest}"
  if [[ -d "${shared}" ]] && [[ -n "$(ls -A "${shared}" 2>/dev/null || true)" ]]; then
    rsync -a "${shared}/" "${dest}/"
  else
    csmon_warn "Shared production data dir is empty; snapshot may be empty"
  fi
  csmon_ok "Data snapshot → ${dest}"
}

csmon_write_slot_compose_override() {
  local slot="$1" port="$2" data_mount="$3" out="$4"
  local bind="${CSMON_BIND_HOST}"
  sed \
    -e "s|\${CSMON_SLOT_BIND}|${bind}|g" \
    -e "s|\${CSMON_SLOT_PORT}|${port}|g" \
    -e "s|\${CSMON_SLOT_DATA_MOUNT}|${data_mount}|g" \
    "${CSMON_DEPLOY_DIR}/compose.slot.override.yml" >"${out}"
}

csmon_health_wait() {
  local port="$1" tries="${2:-30}"
  local url="http://127.0.0.1:${port}${CSMON_HEALTH_PATH}"
  local i
  for ((i = 1; i <= tries; i++)); do
    if curl -fsS "$url" >/dev/null 2>&1; then
      csmon_ok "Health OK ${url}"
      return 0
    fi
    sleep 1
  done
  csmon_warn "Health check did not pass: ${url}"
  return 1
}

csmon_pid_file() {
  echo "${CSMON_DEPLOY_STATE_ROOT}/pids/${1}.pid"
}

csmon_slot_stop_node() {
  local slot="$1"
  local pf
  pf="$(csmon_pid_file "$slot")"
  if [[ -f "$pf" ]]; then
    local pid
    pid="$(cat "$pf")"
    if kill -0 "$pid" 2>/dev/null; then
      kill "$pid" 2>/dev/null || true
      sleep 1
      kill -9 "$pid" 2>/dev/null || true
    fi
    rm -f "$pf"
  fi
}

csmon_docker_container_name() {
  echo "csmon_deploy_${1}"
}

csmon_slot_stop_docker() {
  local slot="$1"
  local name
  name="$(csmon_docker_container_name "$slot")"
  docker rm -f "$name" >/dev/null 2>&1 || true
}

csmon_slot_stop() {
  local slot="$1"
  csmon_state_load
  local rt path
  rt="$(csmon_runtime_resolve)"
  path="$(csmon_slot_path "$slot")"
  case "$rt" in
    docker) csmon_slot_stop_docker "$slot" ;;
    node) csmon_slot_stop_node "$slot" ;;
    *) csmon_die "Invalid runtime: $rt" ;;
  esac
  case "$slot" in
    production) CSMON_PRODUCTION_RUNNING=0 ;;
    preproduction | preprod) CSMON_PREPRODUCTION_RUNNING=0 ;;
  esac
  csmon_state_save
}

csmon_env_for_slot() {
  local slot="$1" port="$2" data_dir="$3"
  export PORT="$port"
  export HOSTNAME="${CSMON_BIND_HOST}"
  export CSMON_BIND_HOST="${CSMON_BIND_HOST}"
  export CSMON_DATA_DIR="$data_dir"
  export NODE_ENV=production
}

csmon_slot_start_docker() {
  local slot="$1" slot_path="$2" port="$3" data_dir="$4"
  local mount name tag
  csmon_require_cmd docker
  mkdir -p "$data_dir"
  mount="$(cd "$data_dir" && pwd)"
  name="$(csmon_docker_container_name "$slot")"
  tag="csmon:deploy-${slot}"

  csmon_info "Building image ${tag}…"
  docker build --pull -t "$tag" -f "${slot_path}/Dockerfile" "$slot_path"

  csmon_slot_stop_docker "$slot"

  csmon_info "Starting ${slot} on ${CSMON_BIND_HOST}:${port} (docker)…"
  docker run -d \
    --name "$name" \
    --restart unless-stopped \
    -p "${CSMON_BIND_HOST}:${port}:3000" \
    -v "${mount}:/app/data" \
    -e NODE_ENV=production \
    -e CSMON_BIND_HOST=0.0.0.0 \
    -e PORT=3000 \
    -e CSMON_DATA_DIR=/app/data \
    --security-opt no-new-privileges:true \
    --cap-drop ALL \
    "$tag"

  csmon_health_wait "$port" || true
}

csmon_slot_start_node() {
  local slot="$1" slot_path="$2" port="$3" data_dir="$4"
  local pf log
  mkdir -p "${CSMON_DEPLOY_STATE_ROOT}/pids"
  pf="$(csmon_pid_file "$slot")"
  log="${CSMON_LOG_DIR}/${slot}.log"

  csmon_slot_stop_node "$slot"

  if [[ ! -d "${slot_path}/.next" ]]; then
    csmon_die "No build in ${slot_path}; run pull-build for ${slot} first"
  fi

  csmon_info "Starting ${slot} on ${CSMON_BIND_HOST}:${port} (node)…"
  (
    cd "$slot_path"
    csmon_env_for_slot "$slot" "$port" "$data_dir"
    csmon_link_env_into_slot "$slot_path"
    nohup ${CSMON_NODE_START} >>"$log" 2>&1 &
    echo $! >"$pf"
  )
  csmon_ok "PID $(cat "$pf") log ${log}"
  csmon_health_wait "$port" || true
}

csmon_slot_start() {
  local slot="$1"
  csmon_init_if_needed
  csmon_state_load
  local rt path port data
  rt="$(csmon_runtime_resolve)"
  path="$(csmon_slot_path "$slot")"
  port="$(csmon_slot_port "$slot")"
  data="$(csmon_data_dir_for_slot "$slot")"
  mkdir -p "$data"

  if [[ "$slot" == "preproduction" || "$slot" == "preprod" ]]; then
    if [[ ! -d "${data}" ]] || [[ -z "$(ls -A "${data}" 2>/dev/null || true)" ]]; then
      csmon_info "Refreshing pre-production data snapshot from production…"
      csmon_snapshot_production_data "${CSMON_SNAPSHOTS_DIR}/preproduction-data"
      CSMON_PREPROD_DATA_SNAPSHOT="${CSMON_SNAPSHOTS_DIR}/preproduction-data"
      csmon_state_save
      data="$(csmon_data_dir_for_slot "$slot")"
    fi
  fi

  case "$rt" in
    docker) csmon_slot_start_docker "$slot" "$path" "$port" "$data" ;;
    node) csmon_slot_start_node "$slot" "$path" "$port" "$data" ;;
    *) csmon_die "Invalid runtime: $rt" ;;
  esac

  case "$slot" in
    production) CSMON_PRODUCTION_RUNNING=1 ;;
    preproduction | preprod) CSMON_PREPRODUCTION_RUNNING=1 ;;
  esac
  csmon_state_save
}

csmon_git_url() {
  local dir="$1"
  git -C "$dir" remote get-url "${CSMON_GIT_REMOTE}" 2>/dev/null || git -C "$dir" remote get-url origin
}

csmon_ensure_preprod_clone() {
  csmon_state_load
  local path="${CSMON_PREPRODUCTION_PATH}"
  if [[ -d "${path}/.git" ]]; then
    return 0
  fi
  csmon_require_cmd git
  local url
  url="$(csmon_git_url "${CSMON_PRODUCTION_PATH}")"
  csmon_info "Cloning pre-production slot from ${url}…"
  git clone "$url" "$path"
}

csmon_pull_build_slot() {
  local slot="$1"
  csmon_init_if_needed
  csmon_state_load
  local path rt
  path="$(csmon_slot_path "$slot")"
  rt="$(csmon_runtime_resolve)"

  if [[ "$slot" == "preproduction" || "$slot" == "preprod" ]]; then
    csmon_ensure_preprod_clone
    path="$(csmon_slot_path "$slot")"
  fi

  if [[ ! -d "${path}/.git" ]]; then
    csmon_die "Not a git checkout: ${path}"
  fi

  csmon_info "Fetching ${CSMON_GIT_REMOTE} in ${path}…"
  git -C "$path" fetch "${CSMON_GIT_REMOTE}"
  git -C "$path" pull --ff-only "${CSMON_GIT_REMOTE}"

  case "$rt" in
    node)
      csmon_require_cmd pnpm
      (cd "$path" && ${CSMON_NODE_INSTALL} && ${CSMON_NODE_BUILD})
      ;;
    docker)
      csmon_require_cmd docker
      docker build --pull -t "csmon:deploy-${slot}" -f "${path}/Dockerfile" "$path"
      ;;
  esac
  csmon_link_env_into_slot "$path"
  csmon_ok "Pull and build finished for ${slot}"
}

csmon_archive_production_code() {
  local ts dest
  ts="$(date -u +%Y%m%dT%H%M%SZ)"
  dest="${CSMON_ARCHIVE_DIR}/production-${ts}"
  csmon_info "Archiving current production code → ${dest}"
  csmon_copy_tree "${CSMON_PRODUCTION_PATH}" "${dest}"
  echo "${dest}"
}

csmon_promote_preprod() {
  csmon_init_if_needed
  csmon_state_load
  csmon_slot_stop production
  csmon_slot_stop preproduction

  local prev pre path
  prev="$(csmon_archive_production_code)"
  CSMON_PREVIOUS_PATH="$prev"
  pre="$(csmon_slot_path preproduction)"
  path="${CSMON_PRODUCTION_PATH}"

  if [[ "$pre" == "$path" ]]; then
    csmon_die "Production and pre-production paths are the same"
  fi

  csmon_info "Promoting pre-production code into production (data and .env unchanged)…"
  csmon_copy_tree "$pre" "$path"
  csmon_link_env_into_slot "$path"
  csmon_sync_shared_env_from_production

  csmon_state_save
  csmon_ok "Promoted. Previous production code: ${prev}"
  csmon_info "Start production when ready (menu or: csmon-deploy start production)"
}

csmon_rollback_production() {
  csmon_init_if_needed
  csmon_state_load
  if [[ -z "${CSMON_PREVIOUS_PATH:-}" || ! -d "${CSMON_PREVIOUS_PATH}" ]]; then
    csmon_die "No previous production archive recorded"
  fi
  csmon_slot_stop production
  csmon_info "Rolling production code back from ${CSMON_PREVIOUS_PATH}…"
  csmon_copy_tree "${CSMON_PREVIOUS_PATH}" "${CSMON_PRODUCTION_PATH}"
  csmon_link_env_into_slot "${CSMON_PRODUCTION_PATH}"
  csmon_state_save
  csmon_ok "Rollback complete. Start production when ready."
}

csmon_copy_production_to_named() {
  local name="$1"
  if [[ ! "$name" =~ ^[a-zA-Z0-9][a-zA-Z0-9_-]{0,31}$ ]]; then
    csmon_die "Invalid slot name: ${name}"
  fi
  csmon_init_if_needed
  local dest="${CSMON_SLOTS_DIR}/${name}"
  csmon_info "Copying production code → slot ${name}…"
  csmon_copy_tree "${CSMON_PRODUCTION_PATH}" "${dest}"
  csmon_link_env_into_slot "${dest}"
  local snap="${CSMON_SNAPSHOTS_DIR}/slot-${name}-data"
  csmon_snapshot_production_data "$snap"
  csmon_ok "Slot ${name} at ${dest} (data snapshot ${snap})"
}

csmon_refresh_preprod_snapshot() {
  csmon_init_if_needed
  csmon_state_load
  local dest="${CSMON_SNAPSHOTS_DIR}/preproduction-data"
  csmon_snapshot_production_data "$dest"
  CSMON_PREPROD_DATA_SNAPSHOT="$dest"
  csmon_state_save
}

csmon_print_status() {
  csmon_init_if_needed
  csmon_state_load
  local rt
  rt="$(csmon_runtime_resolve)"
  echo
  echo "┌─ csmon deploy ─────────────────────────────────────"
  echo "│ State root:    ${CSMON_DEPLOY_STATE_ROOT}"
  echo "│ Runtime:       ${rt}"
  echo "│ Production:    ${CSMON_PRODUCTION_PATH}  →  ${CSMON_BIND_HOST}:$(csmon_slot_port production)"
  echo "│ Pre-production: ${CSMON_PREPRODUCTION_PATH}  →  ${CSMON_BIND_HOST}:$(csmon_slot_port preproduction)"
  echo "│ Shared data:    $(csmon_shared_data_dir)"
  echo "│ Shared env:     $(csmon_shared_env_dir)"
  echo "│ Previous prod:  ${CSMON_PREVIOUS_PATH:-—}"
  echo "│ Preprod data:   ${CSMON_PREPROD_DATA_SNAPSHOT:-$(csmon_data_dir_for_slot preproduction)}"
  echo "└──────────────────────────────────────────────────────"
  echo
  echo "Retained across code swaps (see deploy/manifest.sh):"
  echo "  • Env: ${CSMON_RETAIN_ENV_FILES[*]}"
  echo "  • Live data dir: ${CSMON_DATA_DIR_NAME}/ (SQLite + overrides/feeds.json)"
  echo
}

